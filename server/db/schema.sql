CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    username VARCHAR(30) NOT NULL UNIQUE,
    email VARCHAR(254) UNIQUE,
    phone VARCHAR(20) UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS password_reset_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_password_reset_user_created
    ON password_reset_tokens (user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_password_reset_expiry
    ON password_reset_tokens (expires_at);

CREATE TABLE IF NOT EXISTS password_reset_requests (
    email_hash CHAR(64) PRIMARY KEY,
    last_requested_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS orders (
    order_key CHAR(32) PRIMARY KEY,
    order_id INTEGER NOT NULL UNIQUE CHECK (order_id BETWEEN 100000 AND 999999),
    customer_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    customer_username VARCHAR(30),
    game VARCHAR(120) NOT NULL,
    nominal VARCHAR(255) NOT NULL,
    payment VARCHAR(50) NOT NULL,
    user_id VARCHAR(120) NOT NULL,
    server_id VARCHAR(80) NOT NULL DEFAULT '',
    username VARCHAR(120) NOT NULL DEFAULT '',
    status VARCHAR(16) NOT NULL DEFAULT 'Pending'
        CHECK (status IN ('Pending', 'Processing', 'Success')),
    proof_mime VARCHAR(50) NOT NULL,
    proof_data BYTEA NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_orders_status_created
    ON orders (status, created_at);
CREATE INDEX IF NOT EXISTS idx_orders_created
    ON orders (created_at);
